#!/usr/bin/env python3
"""Generate sound_ids_195.inc from the 1.95 sound-event list (index = native SoundEvent id,
the id ClientboundSoundPacket (0x1a2c40) resolves through the SoundEvent registry vector at
base+0x1430570 +0xe8/+0xf0). First occurrence of a name wins (aliases share ids)."""
import hashlib, json, sys
src = sys.argv[1] if len(sys.argv) > 1 else '/home/codey/minecraft-lce-work/agent-cmd/server/tools/ps4_195_sound_events.json'
out = sys.argv[2] if len(sys.argv) > 2 else 'sound_ids_195.inc'
raw = open(src, 'rb').read()
names = json.loads(raw)
seen = {}
for i, n in enumerate(names):
    if isinstance(n, str) and n and n not in seen:
        seen[n] = i
rows = sorted(seen.items())
with open(out, 'w') as f:
    f.write('/* Generated by tools/gen_sounds.py from %s\n * sha256 %s, %d events, %d unique names. Do not edit. */\n'
            % (src.split('/')[-1], hashlib.sha256(raw).hexdigest(), len(names), len(rows)))
    f.write('#define LCE195_SOUND_EVENT_COUNT %du\n' % len(names))
    f.write('static const struct { const char *name; uint16_t id; } kSounds195[] = {\n')
    for n, i in rows:
        f.write('    {"%s", %d},\n' % (n.replace('\\', '\\\\').replace('"', '\\"'), i))
    f.write('};\n')
print(out, len(rows))
