#!/usr/bin/env python3
"""Generate loader/vanilla_195.inc from tools/data/vanilla_195.json.

Each row: {name, item_id, block_id}. block_id is -1 for plain items. A name
that appears twice (block + separate item, e.g. "bed": block 26 / item 355)
yields one row per registration; lookups prefer the non-block item for item
resolution and the block row for block resolution."""
import json, sys
from pathlib import Path
here = Path(__file__).resolve().parent
data = json.loads((here / 'data' / 'vanilla_195.json').read_text())
rows = []
for it in data['items']:
    rows.append((it['name'], it['id'], it.get('block', -1)))
rows.sort(key=lambda r: (r[0], r[2] >= 0, r[1]))
out = [f"/* generated by tools/gen_vanilla.py from vanilla_195.json; image {data['image_sha256'][:16]}..; {len(rows)} rows */"]
for name, iid, bid in rows:
    assert all(c.islower() or c.isdigit() or c == '_' for c in name), name
    out.append(f'{{"{name}", {iid}, {bid}}},')
dst = Path(sys.argv[1]) if len(sys.argv) > 1 else here.parent / 'loader' / 'vanilla_195.inc'
dst.write_text('\n'.join(out) + '\n')
print(f'wrote {dst} ({len(rows)} rows)')
