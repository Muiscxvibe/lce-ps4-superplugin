uint64_t jmp_word(uintptr_t site, uintptr_t relay) {
    int64_t delta = (int64_t)relay - (int64_t)(site + 5);
    if (delta < INT32_MIN || delta > INT32_MAX) return 0;
    uint32_t rel = (uint32_t)(int32_t)delta;
    return 0x90909000000000e9ull | ((uint64_t)rel << 8);
}

uint64_t patched_word(const Site &s, uintptr_t base, const Relays &r) {
    switch (s.kind) {
    case kFixed: return le64(s.patched);
    case kRenderRelay: return r.render ? jmp_word(base + s.rva, r.render) : 0;
    case kCreateRelay: return r.create ? jmp_word(base + s.rva, r.create) : 0;
    }
    return 0;
}

int apply(uintptr_t base, const Relays &r, const Mem &m, unsigned *changed) {
    if (changed) *changed = 0;
    if (!base || !m.read8 || !m.cas8) return kRefused;
    uint64_t want[kSiteCount], cur[kSiteCount];
    for (size_t i = 0; i < kSiteCount; ++i) {
        want[i] = patched_word(kSites[i], base, r);
        if (!want[i] || ((base + kSites[i].rva) & 7)) return kRefused;
        if (!m.read8(m.ctx, base + kSites[i].rva, &cur[i])) return kRefused;
        if (cur[i] != le64(kSites[i].pristine) && cur[i] != want[i]) return kRefused;  // foreign bytes
    }
    // Record every word with mod_gate BEFORE it changes: the anticheat canonical hash may be
    // taken at any moment (account sign-in), and a record only reverts a word that holds
    // exactly its patched bytes, so recording first is always safe.
    if (m.record)
        for (size_t i = 0; i < kSiteCount; ++i) m.record(m.ctx, base + kSites[i].rva, le64(kSites[i].pristine), want[i]);
    bool done[kSiteCount] = {};
    for (size_t i = 0; i < kSiteCount; ++i) {
        if (cur[i] == want[i]) continue;
        if (!m.cas8(m.ctx, base + kSites[i].rva, cur[i], want[i])) {
            // roll back this call's swaps, newest first
            for (size_t j = i; j-- > 0;)
                if (done[j]) (void)m.cas8(m.ctx, base + kSites[j].rva, want[j], le64(kSites[j].pristine));
            if (changed) *changed = 0;
            return kPartial;
        }
        done[i] = true;
        if (changed) ++*changed;
    }
    return kOk;
}

int diag_apply(uintptr_t base, uintptr_t relays, const Mem &m, unsigned *changed) {
    if (changed) *changed = 0;
    if (!base || !relays || !m.read8 || !m.cas8) return kRefused;
    uint64_t want[kDiagCount];
    for (size_t i = 0; i < kDiagCount; ++i) {
        uint64_t cur = 0;
        want[i] = jmp_word(base + kDiagSites[i].rva, relays + i * kDiagRelayStride);
        if (!want[i] || !m.read8(m.ctx, base + kDiagSites[i].rva, &cur)) return kRefused;
        if (cur != kDiagPrologue && cur != want[i]) return kRefused;
    }
    if (m.record)
        for (size_t i = 0; i < kDiagCount; ++i) m.record(m.ctx, base + kDiagSites[i].rva, kDiagPrologue, want[i]);
    int rc = kOk;
    for (size_t i = 0; i < kDiagCount; ++i) {
        uint64_t cur = 0;
        if (!m.read8(m.ctx, base + kDiagSites[i].rva, &cur) || cur == want[i]) continue;
        if (m.cas8(m.ctx, base + kDiagSites[i].rva, kDiagPrologue, want[i])) { if (changed) ++*changed; }
        else rc = kPartial;  // each word is independent; a missing counter only loses data
    }
    return rc;
}

int diag_revert(uintptr_t base, uintptr_t relays, const Mem &m, unsigned *changed) {
    if (changed) *changed = 0;
    if (!base || !relays || !m.read8 || !m.cas8) return kRefused;
    bool clean = true;
    for (size_t i = 0; i < kDiagCount; ++i) {
        uint64_t cur = 0, want = jmp_word(base + kDiagSites[i].rva, relays + i * kDiagRelayStride);
        if (!m.read8(m.ctx, base + kDiagSites[i].rva, &cur)) { clean = false; continue; }
        if (cur == kDiagPrologue) continue;
        if (want && cur == want && m.cas8(m.ctx, base + kDiagSites[i].rva, cur, kDiagPrologue)) { if (changed) ++*changed; continue; }
        clean = false;
    }
    return clean ? kOk : kPartial;
}

int revert(uintptr_t base, const Relays &r, const Mem &m, unsigned *changed) {
    if (changed) *changed = 0;
    if (!base || !m.read8 || !m.cas8) return kRefused;
    bool clean = true;
    // Slider first (no new Huge selection), relays last.
    for (size_t k = 0; k < kSiteCount; ++k) {
        // slider (5) first so no new Huge selection, then the fixed words, the two relays (4, 6) last
        const size_t idx = k == 0 ? 5 : k < kSiteCount - 2 ? (k <= 4 ? k - 1 : k + 2) : (k == kSiteCount - 2 ? 4 : 6);
        const Site &s = kSites[idx];
        uint64_t cur = 0, pristine = le64(s.pristine), want = patched_word(s, base, r);
        if (!m.read8(m.ctx, base + s.rva, &cur)) { clean = false; continue; }
        if (cur == pristine) continue;
        if (want && cur == want && m.cas8(m.ctx, base + s.rva, cur, pristine)) { if (changed) ++*changed; continue; }
        clean = false;
    }
    return clean ? kOk : kPartial;
}

int biome_cache_prepare(uint8_t *self) {
    int32_t *w = (int32_t *)(self + 0x40), *x0 = (int32_t *)(self + 0x38), *z0 = (int32_t *)(self + 0x3c);
    if (*(void **)(self + 0x48) || *w <= kBiomeCacheWindow) return 0;   // built already, or Large or smaller
    const int32_t cut = (*w - kBiomeCacheWindow) / 2;
    *x0 += cut;
    *z0 += cut;
    *w = kBiomeCacheWindow;
    *(uint32_t *)(self + 0x54) = kBiomeWindowMagic;   // padding of the 0x58-byte object (ctor never writes it)
    return 1;
}

IntArr biome_cache_get_area(void *self, int x, int z, int w, int h, const CacheEnv &env) {
    uint8_t *s = (uint8_t *)self;
    if (!*(void **)(s + 0x48)) {   // first call builds the cache: shrink a Huge window first
        env.lock();
        biome_cache_prepare(s);
        env.unlock();
    }
    const int64_t x0 = *(int32_t *)(s + 0x38), z0 = *(int32_t *)(s + 0x3c), W = *(int32_t *)(s + 0x40);
    const bool huge = *(uint32_t *)(s + 0x54) == kBiomeWindowMagic;
    if (!huge || (x >= x0 && z >= z0 && (int64_t)x + w <= x0 + W && (int64_t)z + h <= z0 + W))
        return env.original(self, x, z, w, h);
    void *parent = *(void **)(s + 0x10);
    GetAreaFn pget = (*(GetAreaFn **)parent)[4];
    env.lock();
    IntArr r = pget(parent, x, z, w, h);
    env.unlock();
    return r;
}

bool want_armed(const Policy &p, uint64_t now_us, bool remote, bool disabled, bool server_off) {
    // Every word computes exactly the retail result for worlds <= 320 chunks, so the words stay armed
    // while joining/joined to an LCE server: the login packet's xzSize reaches the clamp (W3) during the
    // join, before any announcement could be acted on, and a server announcing a Huge world needs them.
    // The anticheat report hashes them canonically (lce_mod_gate_record). worldsize-server.off opts out.
    if ((remote && server_off) || disabled || p.failures >= 3) return false;
    if (!p.first_us || now_us < p.first_us + kBootDelayUs) return false;
    return true;
}

int clamp_xz_compound(int xz) {
    int v = xz < 0x801 ? xz : 0x800;
    return v > 0x35 ? v : 0x36;
}

int render_index(int dim_idx, int cx, int cy, int cz, const int sizes[2], const int offs[2]) {
    if ((unsigned)dim_idx >= 2u || (unsigned)cy > 15u) return -1;
    const int s = sizes[dim_idx], half = s >> 1;
    int x = cx + half, z = cz + half;
    if ((unsigned)x >= (unsigned)s) x = ((x % s) + s) % s;
    if ((unsigned)z >= (unsigned)s) z = ((z % s) + s) % s;
    return (x * s + z) * 16 + cy + offs[dim_idx];
}

